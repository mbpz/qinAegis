// Invoked by the isolated Python harness. Uses only already-installed sandbox Playwright.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require = createRequire(new URL('../sandbox/package.json', import.meta.url));
// Resolve both browser and assertions from the engine's locked Playwright package.
// @playwright/test may resolve a different transitive Playwright/browser revision.
const {chromium, expect} = require('playwright/test');
assert.equal(chromium.executablePath(), require('playwright').chromium.executablePath());
const config = JSON.parse(await fs.readFile(process.argv[2], 'utf8'));
await fs.mkdir(config.output, {recursive:true});
const browser = await chromium.launch({headless:true, ...(process.env.QINAEGIS_TEST_CHROME ? {executablePath:process.env.QINAEGIS_TEST_CHROME} : {})});
const failures = [], blocked = [];
try {
  const context = await browser.newContext({viewport:{width:1440,height:1100}, acceptDownloads:true});
  await context.route('**/*', route => {
    const url = new URL(route.request().url());
    if (url.origin === config.origin || ['blob:','data:'].includes(url.protocol)) return route.continue();
    blocked.push(url.origin); return route.abort();
  });
  await context.addCookies([{name:'qinaegis_session',value:config.cookie,url:config.origin,httpOnly:true,sameSite:'Strict'}]);
  const page = await context.newPage();
  page.on('pageerror', error => failures.push(error.message));
  const nav = async name => page.locator('nav').getByRole('button',{name:new RegExp(name)}).click();
  const select = async (label, option) => { await page.getByRole('button',{name:label,exact:true}).click(); await page.getByRole('option',{name:option}).click(); };
  const rpc = (method, params={}) => page.evaluate(async ({method,params}) => {
    const {csrf}=await (await fetch('/api/v2/session')).json();
    const body=await (await fetch('/api/v2/rpc',{method:'POST',headers:{'Content-Type':'application/json','X-Qinaegis-CSRF':csrf},body:JSON.stringify({id:'browser-fixture',method,params})})).json();
    if(!body.ok) throw Error(body.error?.message || 'fixture RPC failed'); return body.data;
  }, {method,params});
  await page.goto(config.origin);
  await nav('Settings');
  const capture=page.getByRole('region',{name:'Evidence capture policy'});
  await expect(capture.getByText('Saved revision: 1')).toBeVisible();
  await select('Capture mode','Full diagnostics');
  const save=capture.getByRole('button',{name:'Save capture policy',exact:true});
  await expect(save).toBeDisabled();
  await capture.getByRole('checkbox',{name:'Allow sensitive diagnostic content for this saved policy'}).check();
  await capture.getByRole('checkbox',{name:'Confirm this exact capture policy and limits'}).check();
  await expect(save).toBeEnabled();
  await capture.getByRole('spinbutton',{name:'max_events',exact:true}).fill('499');
  await expect(save).toBeDisabled();
  await capture.getByRole('checkbox',{name:'Confirm this exact capture policy and limits'}).check();
  await save.click();
  await expect(capture.getByText(/Policy saved/)).toBeVisible();
  const before=await rpc('getCapturePolicy');
  await rpc('saveCapturePolicy',{expected_revision:before.revision,policy:{...before.policy,max_events:498},approved:true});
  await capture.getByRole('spinbutton',{name:'max_events',exact:true}).fill('497');
  await capture.getByRole('checkbox',{name:'Confirm this exact capture policy and limits'}).check();
  await save.click();
  await expect(capture.getByRole('status')).toContainText('Draft retained');
  await expect(capture.getByRole('spinbutton',{name:'max_events',exact:true})).toHaveValue('497');
  assert.equal((await rpc('getCapturePolicy')).policy.max_events,498);
  await capture.getByRole('button',{name:'Reload capture policy'}).click();
  await expect(capture.getByRole('spinbutton',{name:'max_events',exact:true})).toHaveValue('498');
  await page.screenshot({path:path.join(config.output,'01-policy-cas.png'),fullPage:true});
  console.log('PASS browser policy sensitive confirmation, edit invalidation, save and stale CAS');
  await nav('Reports');
  await page.getByRole('button').filter({has:page.locator('.run-id',{hasText:config.run_id})}).click();
  let process=page.getByRole('region',{name:'Process evidence',exact:true});
  await expect(process).toContainText(config.run_id);
  await process.getByRole('button',{name:'View screenshot-1',exact:true}).click();
  const screenshot=process.getByRole('img',{name:`${config.case_id} / screenshot-1`,exact:true});
  await expect(screenshot).toBeVisible();
  assert.equal(await screenshot.evaluate(image=>image.complete && image.naturalWidth>0),true);
  await process.getByRole('button',{name:`View ${config.artifact.id}`,exact:true}).click();
  await expect(process).toContainText('explicit protocol fixture');
  const downloadPromise=page.waitForEvent('download');
  await process.getByRole('button',{name:`Download ${config.artifact.id}`,exact:true}).click();
  const download=await downloadPromise;
  const downloaded=await fs.readFile(await download.path());
  assert.equal(crypto.createHash('sha256').update(downloaded).digest('hex'),config.artifact.sha256);
  assert.equal(downloaded.length,config.artifact.bytes);
  await page.screenshot({path:path.join(config.output,'02-process-metadata.png'),fullPage:true});
  await fs.unlink(config.artifact_path);
  await nav('Settings'); await nav('Reports');
  await page.getByRole('button').filter({has:page.locator('.run-id',{hasText:config.run_id})}).click();
  process=page.getByRole('region',{name:'Process evidence',exact:true});
  await expect(process).toContainText('unavailable:');
  await expect(process.getByRole('button',{name:`View ${config.artifact.id}`,exact:true})).toBeDisabled();
  await page.screenshot({path:path.join(config.output,'03-missing-attachment.png'),fullPage:true});
  console.log('PASS browser frozen receipt, metadata preview, hashed download and missing attachment');
  await nav('Review');
  await page.getByRole('button',{name:'Inspect source',exact:true}).click();
  const history=page.getByRole('region',{name:'Case revision history'});
  await expect(history).toContainText('Earlier history is unknown');
  // Hold a real revision response while selecting a newer revision. No response is fabricated.
  let releaseOld, sawOld, finishedOld;
  const held=new Promise(resolve=>{releaseOld=resolve;});
  const arrived=new Promise(resolve=>{sawOld=resolve;});
  const finished=new Promise(resolve=>{finishedOld=resolve;});
  let holdRevision=true;
  const holdRoute=async route=>{
    const request=route.request().postDataJSON();
    if(request.method==='getCaseRevision' && request.params.revision===1 && holdRevision) {
      holdRevision=false;
      const response=await route.fetch(); sawOld(); await held;
      await route.fulfill({response}); finishedOld();
    } else await route.continue();
  };
  await page.route('**/api/v2/rpc',holdRoute);
  await select('Historical case revision',/^Revision 1 /);
  await arrived;
  await select('Historical case revision',new RegExp(`^Revision ${config.edited_revision} `));
  await expect(history.locator('pre').first()).toContainText('Edited protocol fixture');
  releaseOld(); await finished;
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  await expect(history.locator('pre').first()).toContainText('Edited protocol fixture');
  await page.unroute('**/api/v2/rpc',holdRoute);
  console.log('PASS browser delayed historical response cannot overwrite newer selection');
  await select('Historical case revision',/^Revision 1 /);
  await expect(history).toContainText('Explicit protocol fixture');
  await history.getByRole('button',{name:'Current inspected content for comparison',exact:true}).click();
  await expect(history).toContainText('Edited protocol fixture');
  const restore=history.getByRole('button',{name:'Create new Draft from this revision'});
  await expect(restore).toBeDisabled();
  await history.getByRole('textbox',{name:'Reason for restoring case revision'}).fill('Browser acceptance: restore original assertions after comparison');
  await history.getByRole('checkbox').check();
  await page.screenshot({path:path.join(config.output,'04-history-comparison.png'),fullPage:true});
  await restore.click();
  await expect(page.getByRole('region',{name:'Inspected case version'})).toHaveCount(0);
  const restored=await rpc('getCaseAsset',{project:config.project,case_id:config.case_id});
  assert.equal(restored.status,'draft'); assert.equal(restored.provenance,null); assert.equal(restored.name,'Explicit protocol fixture');
  const after=await rpc('getCaseHistory',{project:config.project,case_id:config.case_id});
  assert.ok(after.revisions.some(item=>item.operation==='restore' && item.context.reason.includes('Browser acceptance')));
  console.log('PASS browser complete historical/current comparison and reason-confirmed new Draft');
  await nav('Contracts');
  const audit=page.getByRole('region',{name:'Contract change audit'});
  await expect(audit).toContainText('Library revision: 1');
  await audit.getByRole('button',{name:/Revision 1 from/}).click();
  await expect(audit).toContainText('submission returns a receipt');
  await expect(audit).toContainText('Author: local-owner');
  await page.screenshot({path:path.join(config.output,'05-contract-audit.png'),fullPage:true});
  assert.deepEqual(failures,[]); assert.deepEqual(blocked,[]);
  console.log('PASS browser contract before/after audit; no page errors or external requests');
} finally { await browser.close(); }
